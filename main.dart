/// Creates a new, unique product each time it is called.
Product generateProduct() {
  final n = ++_genCounter;
  final title = _newTitles[n % _newTitles.length];
  final rating = double.parse((4.0 + ((n * 7) % 10) / 10).toStringAsFixed(1));
  return Product(
    id: 'new_$n',
    title: title,
    price: '\$${699 + (n * 37) % 600}',
    storage: n.isEven ? '256 GB' : '512 GB',
    rating: rating,
    reviews: 100 + (n * 53) % 2000,
    categories: const ['Smartphones', 'Android', '5G', 'New arrival'],
    description:
        '$title just landed in the catalog. A flagship Android phone with a '
        'bright high-refresh display, a flexible multi-camera system and '
        'fast charging for all-day use.',
    accent: _newAccents[n % _newAccents.length],
  );
}

