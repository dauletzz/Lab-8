// ---- Generator for Pull-to-Refresh -----------------------------------------

int _genCounter = 0;

const List<String> _newTitles = [
  'Samsung Galaxy S26 Ultra',
  'Google Pixel 11 Pro',
  'Xiaomi 17 Pro',
  'OnePlus 14',
  'Nothing Phone (4)',
  'Sony Xperia 1 VIII',
];

